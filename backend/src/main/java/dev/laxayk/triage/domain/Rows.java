package dev.laxayk.triage.domain;

import java.time.Instant;

/** Plain read models returned by the store and the API. */
public final class Rows {
    private Rows() {}

    public record EmailRow(long id, String messageId, String inReplyTo, String refs, String threadKey,
                           String fromAddr, String fromName, String toAddr, String subject, String body,
                           String attachments, boolean autoGenerated, Instant receivedAt, String source,
                           String correlationId, String status, String verdict, String verdictReason,
                           String category, String disposition, Long ticketId) {}

    public record TicketRow(long id, String key, String threadKey, String subject, String requester,
                            String category, String priority, String status, String assignee, String summary,
                            Double confidence, String classifiedBy, boolean needsReview,
                            Instant createdAt, Instant updatedAt) {}

    public record DraftRow(long id, long ticketId, String body, String evidence, String generatedBy,
                           String status, String approvedBy, String bodyHash, Instant createdAt, Instant decidedAt) {}

    public record NotificationRow(long id, Long ticketId, Long emailId, String channel, String target,
                                  String text, boolean delivered, Instant createdAt) {}

    public record EventRow(long id, String correlationId, Long emailId, String stage, String detail,
                           long latencyMs, Instant at) {}

    public record AuditRow(long id, String actor, String action, Long ticketId, Long emailId, String detail, Instant at) {}

    public record UserRow(long id, String username, String passwordHash, String role) {}
}
