-- Agent layer: tool-call trace per draft, vector index for the knowledge base, owner-alert emails in the outbox.
CREATE TABLE draft_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id BIGINT NOT NULL REFERENCES drafts(id),
  step_no INT NOT NULL,
  kind VARCHAR(12) NOT NULL,
  tool VARCHAR(40),
  args TEXT,
  result TEXT,
  latency_ms BIGINT NOT NULL
);
CREATE INDEX idx_draft_steps_draft ON draft_steps(draft_id);

CREATE TABLE kb_chunks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source VARCHAR(200) NOT NULL UNIQUE,
  doc_type VARCHAR(16) NOT NULL,
  title VARCHAR(300) NOT NULL,
  content_sha VARCHAR(64) NOT NULL,
  embedder VARCHAR(80) NOT NULL,
  vector TEXT NOT NULL
);

ALTER TABLE outbox ALTER COLUMN draft_id DROP NOT NULL;
ALTER TABLE outbox ADD COLUMN ticket_id BIGINT;
ALTER TABLE outbox ADD COLUMN kind VARCHAR(16) DEFAULT 'REPLY' NOT NULL;
CREATE INDEX idx_outbox_ticket ON outbox(ticket_id);
