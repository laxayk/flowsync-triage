package dev.laxayk.triage.pipeline;

import dev.laxayk.triage.domain.*;
import dev.laxayk.triage.domain.Rows.EmailRow;
import dev.laxayk.triage.domain.Rows.TicketRow;
import dev.laxayk.triage.gate.GateResult;
import dev.laxayk.triage.gate.SafetyGate;
import dev.laxayk.triage.ingest.Assigner;
import dev.laxayk.triage.llm.Classifier;
import dev.laxayk.triage.agent.DraftAgent;
import dev.laxayk.triage.agent.OwnerAlert;
import dev.laxayk.triage.notify.Notifier;
import dev.laxayk.triage.store.Store;
import dev.laxayk.triage.web.EventHub;
import jakarta.annotation.PreDestroy;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.slf4j.MDC;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.stereotype.Service;

import java.time.Instant;
import java.util.*;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.locks.ReentrantLock;
import java.util.regex.Pattern;

/**
 * Intake and processing. Intake stores the raw mail first (idempotent on Message-ID), then a virtual-thread worker runs
 * gate -> thread match -> classify -> ticket -> notify -> draft. The emails table doubles as the durable queue:
 * anything still RECEIVED at startup is re-queued, so a crash loses nothing.
 */
@Service
public class Pipeline {
    private static final Logger log = LoggerFactory.getLogger(Pipeline.class);
    private static final Pattern REPLY_PREFIX = Pattern.compile("^(\\s*(re|fwd?|aw)\\s*:\\s*)+", Pattern.CASE_INSENSITIVE);
    private static final Pattern MSG_ID = Pattern.compile("<[^>]+>");

    private final Store store;
    private final SafetyGate gate;
    private final Classifier classifier;
    private final DraftAgent drafts;
    private final OwnerAlert ownerAlert;
    private final Assigner assigner;
    private final Notifier notifier;
    private final EventHub hub;
    private final ExecutorService workers = Executors.newVirtualThreadPerTaskExecutor();
    private final ReentrantLock[] threadLocks = new ReentrantLock[64];

    public Pipeline(Store store, SafetyGate gate, Classifier classifier, DraftAgent drafts, Assigner assigner,
                    Notifier notifier, EventHub hub, OwnerAlert ownerAlert) {
        this.ownerAlert = ownerAlert;
        this.store = store;
        this.gate = gate;
        this.classifier = classifier;
        this.drafts = drafts;
        this.assigner = assigner;
        this.notifier = notifier;
        this.hub = hub;
        for (int i = 0; i < threadLocks.length; i++) threadLocks[i] = new ReentrantLock();
    }

    public static String normalizeSubject(String s) {
        return REPLY_PREFIX.matcher(s == null ? "" : s).replaceFirst("").trim().toLowerCase(Locale.ROOT);
    }

    /** Store the mail and queue it. Returns the new email id, or empty when this Message-ID was already seen. */
    public Optional<Long> ingest(ParsedEmail e, String source) {
        if (store.emailExists(e.messageId())) return Optional.empty();
        String corr = UUID.randomUUID().toString().substring(0, 8);
        String threadKey = resolveThread(e);
        String atts = e.attachments().isEmpty() ? null : String.join(", ",
                e.attachments().stream().map(a -> a.name() + " (" + a.type() + ", " + a.size() + " B)").toList());
        Optional<Long> id = store.insertEmail(e.messageId(), e.inReplyTo(), e.references(), threadKey, e.fromAddr(),
                e.fromName(), e.toAddr(), e.subject(), e.body() == null ? "" : e.body(), atts, e.autoGenerated(),
                e.date(), source, corr);
        id.ifPresent(i -> {
            store.event(corr, i, "INTAKE", "stored from " + source, 0);
            hub.publish("email", Map.of("id", i, "state", "received"));
            submit(i);
        });
        return id;
    }

    String resolveThread(ParsedEmail e) {
        List<String> candidates = new ArrayList<>();
        if (e.inReplyTo() != null) candidates.add(e.inReplyTo());
        if (e.references() != null) {
            var m = MSG_ID.matcher(e.references());
            List<String> refs = new ArrayList<>();
            while (m.find()) refs.add(m.group());
            Collections.reverse(refs);
            candidates.addAll(refs);
        }
        for (String c : candidates) {
            Optional<String> k = store.threadKeyForMessageId(c.trim());
            if (k.isPresent()) return k.get();
        }
        if (REPLY_PREFIX.matcher(e.subject()).find()) {
            Optional<TicketRow> t = store.openTicketBySubject(e.fromAddr(), normalizeSubject(e.subject()));
            if (t.isPresent()) return t.get().threadKey();
        }
        return e.messageId();
    }

    public void submit(long emailId) {
        workers.submit(() -> {
            try {
                process(emailId);
            } catch (Exception ex) {
                log.error("Pipeline failed for email {}", emailId, ex);
                store.markEmailProcessed(emailId, "FAILED", null, "pipeline error: " + ex.getClass().getSimpleName(), null, "FAILED", null);
                hub.publish("email", Map.of("id", emailId, "state", "failed"));
            }
        });
    }

    @EventListener(ApplicationReadyEvent.class)
    @org.springframework.core.annotation.Order(20)
    public void requeue() {
        for (EmailRow e : store.emailsByStatus("RECEIVED")) submit(e.id());
    }

    /** Test hook: wait until queued work is finished. */
    public boolean await(long timeoutMs) {
        long end = System.currentTimeMillis() + timeoutMs;
        while (System.currentTimeMillis() < end) {
            if (store.emailsByStatus("RECEIVED").isEmpty()) return true;
            try { Thread.sleep(50); } catch (InterruptedException ie) { Thread.currentThread().interrupt(); return false; }
        }
        return false;
    }

    @PreDestroy
    void shutdown() {
        workers.shutdown();
        try { workers.awaitTermination(5, TimeUnit.SECONDS); } catch (InterruptedException ie) { Thread.currentThread().interrupt(); }
    }

    void process(long emailId) {
        EmailRow row = store.email(emailId).orElse(null);
        if (row == null || !"RECEIVED".equals(row.status())) return;
        MDC.put("corr", row.correlationId());
        ReentrantLock lock = threadLocks[Math.floorMod(row.threadKey().hashCode(), threadLocks.length)];
        lock.lock();
        try {
            // Re-read under the lock: the startup requeue can submit a mail the sample loader already queued,
            // and the second worker must see the first one's result instead of treating the mail as a thread reply.
            row = store.email(emailId).orElse(null);
            if (row == null || !"RECEIVED".equals(row.status())) return;
            ParsedEmail e = toParsed(row);

            long t0 = System.nanoTime();
            GateResult g = gate.evaluate(e);
            store.event(row.correlationId(), emailId, "GATE", g.verdict() + ": " + g.reasonText(), ms(t0));

            if (g.verdict() != Verdict.CLEAN) {
                String category = switch (g.verdict()) {
                    case SPAM -> Category.SPAM.name();
                    case SALES -> Category.SALES.name();
                    case AUTO_REPLY -> Category.IRRELEVANT.name();
                    default -> null;
                };
                store.markEmailProcessed(emailId, "PROCESSED", g.verdict().name(), g.reasonText(), category,
                        g.verdict().disposition(), null);
                if (g.verdict().disposition().equals("SECURITY_HOLD"))
                    notifier.notifySecurity(emailId, "Security hold: " + g.verdict() + " mail from "
                            + Notifier.sanitize(row.fromAddr()) + ". Needs human review before anything else happens.");
                hub.publish("email", Map.of("id", emailId, "state", "held", "verdict", g.verdict().name()));
                return;
            }

            Optional<TicketRow> existing = store.ticketByThread(row.threadKey());
            if (existing.isPresent()) {
                TicketRow t = existing.get();
                store.markEmailProcessed(emailId, "PROCESSED", "CLEAN", g.reasonText(), t.category(), "THREADED", t.id());
                store.reopenTicket(t.id());
                store.touchTicket(t.id());
                store.event(row.correlationId(), emailId, "THREAD", "attached to " + t.key(), 0);
                notifier.notifyAssignee(t.id(), emailId, t.assignee(), t.key() + " has a new reply from "
                        + Notifier.sanitize(row.fromAddr()) + ": " + Notifier.sanitize(row.subject()));
                hub.publish("ticket", Map.of("id", t.id(), "state", "updated"));
                return;
            }

            long t1 = System.nanoTime();
            Classification c = classifier.classify(e);
            store.event(row.correlationId(), emailId, "CLASSIFY", c.category() + " " + c.priority() + " via " + c.source()
                    + (c.needsReview() ? " (needs review)" : ""), ms(t1));
            createOrSkip(row, e, c);
        } finally {
            lock.unlock();
            MDC.remove("corr");
        }
    }

    /** Human released a held mail: classify it and create a ticket flagged for review. */
    public Optional<Long> release(long emailId, String actor) {
        EmailRow row = store.email(emailId).orElse(null);
        if (row == null || row.ticketId() != null || !List.of("SECURITY_HOLD", "QUARANTINED", "NO_TICKET").contains(row.disposition()))
            return Optional.empty();
        ParsedEmail e = toParsed(row);
        Classification c = classifier.classify(e);
        c = new Classification(c.category().ticketable() ? c.category() : Category.QUERY, c.priority(), c.summary(),
                c.confidence(), c.source(), true, "released by " + actor);
        store.audit(actor, "RELEASE_EMAIL", null, emailId, "gate verdict was " + row.verdict());
        Optional<Long> id = createTicket(row, e, c, true);
        id.ifPresent(i -> hub.publish("ticket", Map.of("id", i, "state", "created")));
        return id;
    }

    private void createOrSkip(EmailRow row, ParsedEmail e, Classification c) {
        if (!c.category().ticketable()) {
            String why = c.category() == Category.IRRELEVANT ? "Possibly unrelated, kept for review (not deleted): " + c.reason() : c.reason();
            store.markEmailProcessed(row.id(), "PROCESSED", "CLEAN", why, c.category().name(), "NO_TICKET", null);
            hub.publish("email", Map.of("id", row.id(), "state", "no_ticket"));
            return;
        }
        Optional<Long> id = createTicket(row, e, c, false);
        id.ifPresent(i -> hub.publish("ticket", Map.of("id", i, "state", "created")));
    }

    private Optional<Long> createTicket(EmailRow row, ParsedEmail e, Classification c, boolean fromRelease) {
        String priority = c.priority();
        String assignee = assigner.ownerFor(c.category());
        String subject = REPLY_PREFIX.matcher(row.subject()).replaceFirst("").trim();
        long tid = store.insertTicket(row.threadKey(), subject, row.fromAddr(), c.category().name(), priority, assignee,
                c.summary(), c.confidence(), c.source(), c.needsReview());
        store.markEmailProcessed(row.id(), "PROCESSED", fromRelease ? row.verdict() : "CLEAN", c.reason(),
                c.category().name(), "TICKET", tid);
        TicketRow t = store.ticket(tid).orElseThrow();
        store.event(row.correlationId(), row.id(), "TICKET", t.key() + " assigned to " + (assignee == null ? "nobody" : assignee), 0);
        notifier.notifyAssignee(tid, row.id(), assignee, t.key() + " [" + priority + " " + c.category() + "] "
                + Notifier.sanitize(subject) + (assignee == null ? "" : " -> " + assignee));

        if (EnumSet.of(Category.QUERY, Category.BILLING, Category.ACCOUNT_ACCESS).contains(c.category())) {
            long t2 = System.nanoTime();
            try {
                DraftAgent.Result d = drafts.write(e, c.category(), tid);
                long draftId = store.insertDraft(tid, d.body(), String.join("; ", d.evidence()), d.generatedBy());
                int n = 1;
                for (DraftAgent.Step s : d.steps()) store.insertDraftStep(draftId, n++, s.kind(), s.tool(), s.args(), s.result(), s.latencyMs());
                if (d.needsHuman()) store.flagReview(tid);
                if (!d.warnings().isEmpty()) store.event(row.correlationId(), row.id(), "DRAFT_CHECK", String.join("; ", d.warnings()), 0);
                if (d.gap()) store.event(row.correlationId(), row.id(), "KB_GAP", "no document answered: " + Notifier.sanitize(row.subject()), 0);
                store.event(row.correlationId(), row.id(), "DRAFT", "by " + d.generatedBy() + ", " + d.steps().size() + " steps, evidence " + d.evidence()
                        + (d.needsHuman() ? ", needs human" : ""), ms(t2));
            } catch (RuntimeException ex) {
                log.warn("Draft agent failed for {}: {}", t.key(), ex.getMessage());
                store.event(row.correlationId(), row.id(), "DRAFT", "failed: " + ex.getClass().getSimpleName(), ms(t2));
            }
        }
        long t3 = System.nanoTime();
        Optional<String> alerted = ownerAlert.alert(t, e, c.category());
        alerted.ifPresent(to -> store.event(row.correlationId(), row.id(), "OWNER_MAIL", "briefed " + to, ms(t3)));
        return Optional.of(tid);
    }

    private static long ms(long startNanos) { return (System.nanoTime() - startNanos) / 1_000_000; }

    static ParsedEmail toParsed(EmailRow r) {
        List<ParsedEmail.Attachment> atts = new ArrayList<>();
        if (r.attachments() != null) {
            for (String a : r.attachments().split(", (?=[^,]*\\()")) {
                int p = a.lastIndexOf(" (");
                atts.add(new ParsedEmail.Attachment(p > 0 ? a.substring(0, p) : a, "", 0));
            }
        }
        return new ParsedEmail(r.messageId(), r.inReplyTo(), r.refs(), r.fromAddr(), r.fromName(), r.toAddr(),
                r.subject(), r.body(), r.receivedAt() == null ? Instant.now() : r.receivedAt(), r.autoGenerated(), atts);
    }
}
