CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(16) NOT NULL
);

CREATE TABLE tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_key VARCHAR(300) NOT NULL UNIQUE,
  subject VARCHAR(500) NOT NULL,
  requester VARCHAR(320) NOT NULL,
  category VARCHAR(32) NOT NULL,
  priority VARCHAR(4) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
  assignee VARCHAR(64),
  summary TEXT,
  confidence DOUBLE PRECISION,
  classified_by VARCHAR(80),
  needs_review BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE emails (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id VARCHAR(500) NOT NULL UNIQUE,
  in_reply_to VARCHAR(500),
  refs TEXT,
  thread_key VARCHAR(300),
  from_addr VARCHAR(320) NOT NULL,
  from_name VARCHAR(200),
  to_addr VARCHAR(320),
  subject VARCHAR(500) NOT NULL,
  body TEXT NOT NULL,
  attachments TEXT,
  auto_generated BOOLEAN NOT NULL DEFAULT FALSE,
  received_at TIMESTAMP WITH TIME ZONE NOT NULL,
  source VARCHAR(16) NOT NULL,
  correlation_id VARCHAR(40) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'RECEIVED',
  verdict VARCHAR(24),
  verdict_reason TEXT,
  category VARCHAR(32),
  disposition VARCHAR(20),
  ticket_id BIGINT REFERENCES tickets(id)
);
CREATE INDEX idx_emails_ticket ON emails(ticket_id);
CREATE INDEX idx_emails_status ON emails(status);

CREATE TABLE drafts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES tickets(id),
  body TEXT NOT NULL,
  evidence TEXT,
  generated_by VARCHAR(80),
  status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  approved_by VARCHAR(64),
  body_hash VARCHAR(64),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  decided_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id BIGINT NOT NULL REFERENCES drafts(id),
  recipient VARCHAR(320) NOT NULL,
  subject VARCHAR(500) NOT NULL,
  body TEXT NOT NULL,
  mode VARCHAR(10) NOT NULL,
  sent_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT REFERENCES tickets(id),
  email_id BIGINT REFERENCES emails(id),
  channel VARCHAR(16) NOT NULL,
  target VARCHAR(100) NOT NULL,
  text TEXT NOT NULL,
  delivered BOOLEAN NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(64) NOT NULL,
  action VARCHAR(40) NOT NULL,
  ticket_id BIGINT,
  email_id BIGINT,
  detail TEXT,
  at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE pipeline_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correlation_id VARCHAR(40) NOT NULL,
  email_id BIGINT,
  stage VARCHAR(24) NOT NULL,
  detail TEXT,
  latency_ms BIGINT NOT NULL,
  at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_events_email ON pipeline_events(email_id);
